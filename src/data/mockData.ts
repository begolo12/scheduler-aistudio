const now = new Date();
const getISOWithHour = (daysOffset: number, hour: number, minute: number = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() + daysOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

